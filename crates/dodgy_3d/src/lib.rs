/// A single agent in the simulation.
#[derive(Clone, PartialEq, Debug)]
pub struct Agent {
  /// The position of the agent.
  pub position: Vec3,
  /// The current velocity of the agent.
  pub velocity: Vec3,

  /// The radius of the agent. Agents will use this to avoid bumping into each
  /// other.
  pub radius: f32,
  /// The amount of responsibility an agent has to avoid other agents. The
  /// amount of avoidance between two agents is then dependent on the ratio of
  /// the responsibility between the agents. Note this does not affect
  /// avoidance of obstacles.
  pub avoidance_responsibility: f32,
}

/// A point of the known future path of an agent.
#[derive(Clone, Copy, PartialEq, Debug)]
pub struct PathPoint {
  /// The time from now when the agent is at `position`. Must be positive.
  pub time: f32,
  /// The position of the agent at `time`.
  pub position: Vec3,
}

/// Parameters for computing the avoidance vector.
#[derive(Clone, PartialEq, Debug)]
pub struct AvoidanceOptions {
  /// How long in the future should collisions be considered between agents.
  pub time_horizon: f32,
}

impl Agent {
  /// Computes a velocity based off the agent's preferred velocity (usually the
  /// direction to its current goal/waypoint). This new velocity is intended to
  /// avoid running into the agent's `neighbours`. This is not always possible,
  /// but agents will attempt to resolve any collisions in a reasonable fashion.
  /// The `max_speed` is the maximum magnitude of the returned velocity. Even if
  /// the `preferred_velocity` is larger than `max_speed`, the resulting vector
  /// will be at most `max_speed` in length. The `time_step` helps determine the
  /// velocity in cases of existing collisions, and must be positive.
  pub fn compute_avoiding_velocity(
    &self,
    neighbours: &[Cow<'_, Agent>],
    preferred_velocity: Vec3,
    max_speed: f32,
    time_step: f32,
    avoidance_options: &AvoidanceOptions,
  ) -> Vec3 {
    self
      .compute_avoiding_velocity_internal(
        neighbours.iter().map(|neighbour| (neighbour.as_ref(), &[][..])),
        preferred_velocity,
        max_speed,
        time_step,
        avoidance_options,
      )
      .0
  }

  #[cfg(feature = "debug")]
  /// Same as [`Self::compute_avoiding_velocity`], but additionally provides
  /// debug data in the form of the plane constraints generated by each agent.
  pub fn compute_avoiding_velocity_with_debug(
    &self,
    neighbours: &[Cow<'_, Agent>],
    preferred_velocity: Vec3,
    max_speed: f32,
    time_step: f32,
    avoidance_options: &AvoidanceOptions,
  ) -> (Vec3, Vec<Plane>) {
    self.compute_avoiding_velocity_internal(
      neighbours.iter().map(|neighbour| (neighbour.as_ref(), &[][..])),
      preferred_velocity,
      max_speed,
      time_step,
      avoidance_options,
    )
  }

  /// Same as [`Self::compute_avoiding_velocity`], but the future path of each
  /// neighbour can be given, instead of assuming that it keeps its velocity.
  /// The path starts at the current position of the neighbour at time zero, and
  /// consists of straight lines between its points. Their times must be
  /// positive and increasing. After its last point, the neighbour keeps the
  /// velocity of the last line. The velocity of a neighbour with a path is only
  /// used while already colliding with it. A neighbour with an empty path keeps
  /// its velocity.
  pub fn compute_avoiding_velocity_with_paths(
    &self,
    neighbours: &[(Cow<'_, Agent>, &[PathPoint])],
    preferred_velocity: Vec3,
    max_speed: f32,
    time_step: f32,
    avoidance_options: &AvoidanceOptions,
  ) -> Vec3 {
    self
      .compute_avoiding_velocity_internal(
        neighbours.iter().map(|(neighbour, path)| (neighbour.as_ref(), *path)),
        preferred_velocity,
        max_speed,
        time_step,
        avoidance_options,
      )
      .0
  }

  #[cfg(feature = "debug")]
  /// Same as [`Self::compute_avoiding_velocity_with_paths`], but additionally
  /// provides debug data in the form of the plane constraints generated by each
  /// agent.
  pub fn compute_avoiding_velocity_with_paths_and_debug(
    &self,
    neighbours: &[(Cow<'_, Agent>, &[PathPoint])],
    preferred_velocity: Vec3,
    max_speed: f32,
    time_step: f32,
    avoidance_options: &AvoidanceOptions,
  ) -> (Vec3, Vec<Plane>) {
    self.compute_avoiding_velocity_internal(
      neighbours.iter().map(|(neighbour, path)| (neighbour.as_ref(), *path)),
      preferred_velocity,
      max_speed,
      time_step,
      avoidance_options,
    )
  }

  /// The implementation of [`Self::compute_avoiding_velocity`] and
  /// [`Self::compute_avoiding_velocity_with_paths`]. Neighbours with an empty
  /// path keep their velocity.
  fn compute_avoiding_velocity_internal<'a>(
    &self,
    neighbours: impl Iterator<Item = (&'a Agent, &'a [PathPoint])>,
    preferred_velocity: Vec3,
    max_speed: f32,
    time_step: f32,
    avoidance_options: &AvoidanceOptions,
  ) -> (Vec3, Vec<Plane>) {
    assert!(time_step > 0.0, "time_step must be positive, was {}", time_step);

    let planes = neighbours
      .map(|(neighbour, path)| {
        self.get_plane_for_neighbour_path(
          neighbour,
          path,
          avoidance_options.time_horizon,
          time_step,
        )
      })
      .collect::<Vec<Plane>>();

    (solve_linear_program(&planes, max_speed, preferred_velocity), planes)
  }

  /// Same as [`Self::get_plane_for_neighbour`], but for a `neighbour` that
  /// follows `path` instead of keeping its velocity, unless `path` is empty.
  fn get_plane_for_neighbour_path(
    &self,
    neighbour: &Agent,
    path: &[PathPoint],
    time_horizon: f32,
    time_step: f32,
  ) -> Plane {
    let sum_radius = self.radius + neighbour.radius;
    let mut start_position = neighbour.position - self.position;

    // Existing collisions are resolved within `time_step`, where the path does
    // not matter.
    if path.is_empty()
      || start_position.length_squared() <= sum_radius * sum_radius
    {
      return self.get_plane_for_neighbour(neighbour, time_horizon, time_step);
    }

    // Each line of the path has its own velocity obstacle, and the velocity
    // obstacle of the path is their union. Find the one that the agent's
    // velocity is the deepest inside of, or if it's not inside any of them, the
    // nearest one.
    let mut signed_distance = f32::INFINITY;
    let mut vo_normal = Vec3::ZERO;

    let mut start_time = 0.0;
    for (index, point) in path.iter().enumerate() {
      assert!(
        point.time > start_time,
        "path times must be positive and increasing, found {} after {}",
        point.time,
        start_time
      );

      let end_position = point.position - self.position;
      let line_velocity =
        (end_position - start_position) / (point.time - start_time);
      // The last line continues until the time horizon.
      let end_time = if index + 1 == path.len() {
        time_horizon
      } else {
        point.time.min(time_horizon)
      };

      let (line_signed_distance, line_normal) = project_to_line_obstacle(
        start_position - line_velocity * start_time,
        self.velocity - line_velocity,
        sum_radius,
        start_time,
        end_time,
      );
      if line_signed_distance < signed_distance {
        signed_distance = line_signed_distance;
        vo_normal = line_normal;
      }

      if point.time >= time_horizon {
        break;
      }
      start_time = point.time;
      start_position = end_position;
    }

    self.get_plane_for_projection(
      neighbour,
      vo_normal * -signed_distance,
      vo_normal,
      /* inside_vo= */ signed_distance < 0.0,
    )
  }

  /// Creates a plane to describe the half-space of valid velocities that should
  /// not collide with `neighbour`.
  fn get_plane_for_neighbour(
    &self,
    neighbour: &Agent,
    time_horizon: f32,
    time_step: f32,
  ) -> Plane {
    // There are two parts to the velocity obstacle induced by `neighbour`.
    // 1) The cut-off sphere. This is where the agent collides with `neighbour`
    // after some time (either `time_horizon` or `time_step`).
    // 2) The cut-off shadow. Any velocity that is just scaled up from a
    // velocity in the cut-off sphere will also hit `neighbour`.
    //
    // If the relative position and velocity is used, the cut-off for the shadow
    // will be directed toward the origin.

    let relative_neighbour_position = neighbour.position - self.position;
    let relative_agent_velocity = self.velocity - neighbour.velocity;

    let distance_squared = relative_neighbour_position.length_squared();

    let sum_radius = self.radius + neighbour.radius;
    let sum_radius_squared = sum_radius * sum_radius;

    let vo_normal;
    let relative_velocity_projected_to_vo;
    let inside_vo;

    // Find out if the agent is inside the cut-off sphere. Note: since both the
    // distance to the cut-off sphere and the radius of the cut-off sphere is
    // scaled by `time_horizon` (or `time_step` depending on the situation),
    // factoring out those terms and cancelling yields this simpler expression.
    if distance_squared > sum_radius_squared {
      // No collision, so either project on to the cut-off sphere, or the
      // cut-off shadow.
      //
      // The edges of the cut-off shadow lies along the tangents of the sphere
      // that intersects the origin (since the tangents are the planes that just
      // graze the cut-off sphere and so these planes divide the "shadowed"
      // velocities from the "unshadowed" velocities).
      //
      // Since the shadows are caused by the tangent "ring", velocities should
      // be projected to the cut-off sphere when they are on one-side of
      // the tangent ring, and should be projected to the shadow when on
      // the other-side of the tangent ring.

      let cutoff_sphere_center = relative_neighbour_position / time_horizon;
      let cutoff_sphere_center_to_relative_velocity =
        relative_agent_velocity - cutoff_sphere_center;
      let cutoff_sphere_center_to_relative_velocity_length_squared =
        cutoff_sphere_center_to_relative_velocity.length_squared();

      let dot = cutoff_sphere_center_to_relative_velocity
        .dot(relative_neighbour_position);

      // TODO: Figure out why this works.
      if dot < 0.0
        && dot * dot
          > sum_radius_squared
            * cutoff_sphere_center_to_relative_velocity_length_squared
      {
        // The relative velocity has not gone past the cut-off sphere tangent
        // ring yet, so project onto the cut-off sphere.

        let cutoff_sphere_radius = sum_radius / time_horizon;

        vo_normal =
          cutoff_sphere_center_to_relative_velocity.normalize_or_zero();
        relative_velocity_projected_to_vo =
          vo_normal * cutoff_sphere_radius + cutoff_sphere_center;
        inside_vo = cutoff_sphere_center_to_relative_velocity_length_squared
          < cutoff_sphere_radius * cutoff_sphere_radius;
      } else {
        // The relative velocity is past the cut-off sphere tangent ring, so
        // project onto the shadow (which is a cone). Note this means we can
        // ignore the time_horizon, since the cone is the same regardless of the
        // time horizon.

        // We want to find the normal of the tangent plane nearest to the
        // relative velocity. Find the direction from the axis of the cone to
        // the relative velocity. If the velocity is on the axis, all directions
        // are equally good, as long as the neighbour uses the opposite one. The
        // neighbour has the opposite axis, for which `any_orthogonal_vector`
        // returns the opposite vector.
        let distance = distance_squared.sqrt();
        let axis = relative_neighbour_position / distance;
        let side = axis
          .cross(relative_agent_velocity)
          .cross(axis)
          .try_normalize()
          .unwrap_or_else(|| axis.any_orthogonal_vector().normalize());

        // Consider the right triangle of zero, the center of the sphere at
        // `relative_neighbour_position`, and its tangent point. The hypotenuse
        // has length `distance`, and the leg to the center has length
        // `sum_radius`. The normal is in the direction of this leg, so it's
        // composed of the directions `side` and `axis` using the ratios of the
        // triangle.
        let tangent_triangle_leg =
          (distance_squared - sum_radius_squared).sqrt();
        vo_normal =
          (side * tangent_triangle_leg - axis * sum_radius) / distance;

        let distance_to_plane = Plane { normal: vo_normal, point: Vec3::ZERO }
          .signed_distance_to_plane(relative_agent_velocity);
        inside_vo = distance_to_plane < 0.0;
        relative_velocity_projected_to_vo =
          relative_agent_velocity - distance_to_plane * vo_normal;
      }
    } else {
      // Collision. Project on cut-off sphere at time `time_step`.

      // Find the velocity such that after `time_step` the agent would be at the
      // neighbours position.
      let cutoff_sphere_center = relative_neighbour_position / time_step;
      let cutoff_sphere_radius = sum_radius / time_step;

      // The direction of the velocity from `cutoff_sphere_center` is therefore
      // the normal to the velocity obstacle.
      vo_normal = {
        let velocity_from_circle_center =
          relative_agent_velocity - cutoff_sphere_center;
        // If the vector has a length of zero, pick a random direction. Fork the
        // implementation of `normalize_or` so we only compute random
        // values if necessary (which should be very rare).
        let recip = velocity_from_circle_center.length_recip();
        if recip.is_finite() && recip > 0.0 {
          velocity_from_circle_center * recip
        } else {
          // Generate uniform random point based on
          // https://math.stackexchange.com/a/1586015
          let z: f32 = rand::random();
          let longitude: f32 = rand::random();

          let z_normalize = (1.0 - z * z).sqrt();
          Vec3::new(
            longitude.cos() * z_normalize,
            longitude.sin() * z_normalize,
            z,
          )
        }
      };
      // Get the point on the cut-off sphere in that direction (which is the
      // agent's velocity projected to the sphere).
      relative_velocity_projected_to_vo =
        vo_normal * cutoff_sphere_radius + cutoff_sphere_center;
      inside_vo = true;
    }

    // As in the paper, `u` is the vector from the relative velocity to the
    // nearest point outside the velocity obstacle.
    let u = relative_velocity_projected_to_vo - relative_agent_velocity;

    self.get_plane_for_projection(neighbour, u, vo_normal, inside_vo)
  }

  /// Creates the plane at the projection of the agent's velocity to the
  /// velocity obstacle of `neighbour`. `u` is the vector to the projection,
  /// `vo_normal` is the normal of the velocity obstacle there, and `inside_vo`
  /// is whether the velocity is inside the velocity obstacle.
  fn get_plane_for_projection(
    &self,
    neighbour: &Agent,
    u: Vec3,
    vo_normal: Vec3,
    inside_vo: bool,
  ) -> Plane {
    let responsibility = if inside_vo {
      self.avoidance_responsibility
        / (self.avoidance_responsibility + neighbour.avoidance_responsibility)
    } else {
      1.0
    };

    Plane { point: self.velocity + u * responsibility, normal: vo_normal }
  }
}

/// Projects `relative_velocity` to the velocity obstacle of a neighbour that is
/// on a straight line from `start_time` to `end_time`. Returns the signed
/// distance from the velocity obstacle (negative inside) and its normal there.
/// `origin` is the position of the neighbour at time zero if it was always on
/// this line (which does not have to be true), relative to the agent.
/// `relative_velocity` is the velocity of the agent relative to the neighbour.
///
/// The velocities that collide at exactly `time` are in a sphere with a center
/// of `origin / time` and a radius of `sum_radius / time`. The velocity
/// obstacle is the union of these spheres: the cut-off sphere of `end_time`,
/// its shadow, and the sphere of `start_time` where the shadow ends.
fn project_to_line_obstacle(
  origin: Vec3,
  relative_velocity: Vec3,
  sum_radius: f32,
  start_time: f32,
  end_time: f32,
) -> (f32, Vec3) {
  // The signed distance from a sphere is a convex function of its inverse time,
  // so the sphere to project to is the one with the smallest signed distance,
  // clamped to the line. The maximum is infinity if `start_time` is zero.
  let max_inverse_time = 1.0 / start_time;
  let min_inverse_time = 1.0 / end_time;

  let distance_squared = origin.length_squared();
  let tangent_length_squared = distance_squared - sum_radius * sum_radius;

  let inverse_time = if tangent_length_squared > 0.0 {
    let tangent_length = tangent_length_squared.sqrt();
    let cross = origin.cross(relative_velocity);
    let inverse_time = (origin.dot(relative_velocity)
      + cross.length() * sum_radius / tangent_length)
      / distance_squared;

    if min_inverse_time <= inverse_time && inverse_time <= max_inverse_time {
      // Project to the shadow. Its tangent planes go through zero, so this does
      // not need the sphere, which can be inaccurate as it can be very large.
      // Heading exactly to the center, all sides are equally good.
      let side = cross
        .cross(origin)
        .try_normalize()
        .unwrap_or_else(|| origin.any_orthogonal_vector().normalize());
      let distance = distance_squared.sqrt();
      let normal =
        (side * tangent_length - origin * (sum_radius / distance)) / distance;
      return (normal.dot(relative_velocity), normal);
    }

    inverse_time.min(max_inverse_time).max(min_inverse_time)
  } else {
    // Zero is inside all of the spheres, so the larger spheres contain the
    // smaller ones.
    max_inverse_time
  };

  // Project to the sphere. From its center, prefer moving to the side.
  let center_to_velocity = relative_velocity - origin * inverse_time;
  let normal = center_to_velocity
    .try_normalize()
    .unwrap_or_else(|| origin.any_orthogonal_vector().normalize_or(Vec3::X));
  (normal.dot(center_to_velocity) - sum_radius * inverse_time, normal)
}

